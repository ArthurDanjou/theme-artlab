import type { GetThemeOptions } from './helper'
import { createThemeHelpers } from './helper'

export interface ObsidianManifestOptions extends GetThemeOptions {
  version: string
}

/** Strip alpha channel from hex colors (e.g. #dbd7caee → #dbd7ca) */
function stripAlpha(hex: string): string {
  if (hex.startsWith('#') && hex.length === 9)
    return hex.slice(0, 7)
  return hex
}

function modeVars(color: 'light' | 'dark'): Record<string, string> {
  const { v } = createThemeHelpers({ color, name: color === 'light' ? 'ArtLab Light' : 'ArtLab Dark' })

  const background = v('background')!
  const activeBackground = v('activeBackground')!
  const softActiveBackground = v('softActiveBackground')!
  const foreground = v('foreground')!
  const secondaryForeground = v('secondaryForeground')!
  const activeForeground = v('activeForeground')!
  const primary = v('primary')!
  const border = v('border')!
  const ignored = v('ignored')!
  const faded = v('faded')!

  return {
    // Base colors
    '--color-red': v('red')!,
    '--color-orange': v('orange')!,
    '--color-yellow': v('yellow')!,
    '--color-green': v('green')!,
    '--color-cyan': v('cyan')!,
    '--color-blue': v('blue')!,
    '--color-purple': v('keyword')!,
    '--color-pink': v('magenta')!,

    // Backgrounds
    '--background-primary': background,
    '--background-primary-alt': activeBackground,
    '--background-secondary': activeBackground,
    '--background-secondary-alt': softActiveBackground,
    '--background-modifier-border': border,
    '--background-modifier-form-field': activeBackground,
    '--background-modifier-form-field-highlighted': softActiveBackground,
    '--background-modifier-box-shadow': stripAlpha(faded),
    '--background-modifier-success': v('green')!,
    '--background-modifier-error': v('red')!,
    '--background-modifier-error-rgb': '243, 139, 168',
    '--background-modifier-error-hover': v('red')!,
    '--background-modifier-cover': stripAlpha(ignored),
    '--background-modifier-message': activeBackground,

    // Text
    '--text-normal': foreground,
    '--text-muted': secondaryForeground,
    '--text-faint': ignored,
    '--text-accent': primary,
    '--text-accent-hover': primary,
    '--text-on-accent': color === 'light' ? '#ffffff' : stripAlpha(v('background')!),
    '--text-error': v('red')!,
    '--text-success': v('green')!,
    '--text-warning': v('orange')!,

    // Interactive
    '--interactive-normal': activeBackground,
    '--interactive-hover': softActiveBackground,
    '--interactive-accent': primary,
    '--interactive-accent-hover': primary,
    '--interactive-accent-rgb': '116, 199, 236',
    '--interactive-success': v('green')!,

    // Scrollbars
    '--scrollbar-active-thumb-bg': ignored,
    '--scrollbar-bg': stripAlpha(faded),
    '--scrollbar-thumb-bg': stripAlpha(ignored),

    // Radius
    '--radius-s': '4px',
    '--radius-m': '8px',
    '--radius-l': '12px',

    // Icons
    '--icon-color': activeForeground,
    '--icon-color-hover': foreground,
    '--icon-color-active': primary,
    '--icon-color-focused': primary,

    // Code / syntax
    '--code-background': activeBackground,
    '--code-normal': foreground,
    '--code-comment': v('comment')!,
    '--code-function': v('function')!,
    '--code-important': v('red')!,
    '--code-keyword': v('keyword')!,
    '--code-operator': v('operator')!,
    '--code-property': v('property')!,
    '--code-punctuation': v('punctuation')!,
    '--code-string': v('string')!,
    '--code-tag': v('keyword')!,
    '--code-value': v('number')!,

    // Misc
    '--divider-color': border,
    '--blockquote-border-color': border,
    '--table-border-color': border,
    '--hr-color': border,
    '--link-color': primary,
    '--link-color-hover': primary,
    '--link-external-color': primary,
    '--tag-color': primary,
    '--tag-background': activeBackground,
  }
}

export function getObsidianTheme(): string {
  const light = modeVars('light')
  const dark = modeVars('dark')

  const toCss = (vars: Record<string, string>) =>
    Object.entries(vars)
      .map(([key, value]) => `  ${key}: ${value};`)
      .join('\n')

  return `/* ArtLab Theme for Obsidian */
/* Generated by artlab-theme. Do not edit by hand. */

body.theme-light {
${toCss(light)}
}

body.theme-dark {
${toCss(dark)}
}

/* Accent selection */
::selection {
  background: var(--interactive-accent);
  color: var(--text-on-accent);
}
`
}

export function getObsidianManifest(options: ObsidianManifestOptions) {
  return {
    name: 'ArtLab',
    version: options.version,
    minAppVersion: '1.0.0',
    description: 'ArtLab theme: the clarity of Vitesse with the cozy Catppuccin palette.',
    author: 'Arthur Danjou',
    authorUrl: 'https://github.com/arthurdanjou',
  }
}
